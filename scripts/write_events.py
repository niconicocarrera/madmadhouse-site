#!/usr/bin/env python3
"""Write web/src/data/events.ts from the reviewed drafts.

Deliberately a separate step from extraction: extraction is re-runnable and
exploratory, this commits a result into the app. Nothing else in the app may
import events.ts; reads go through getEvents.ts (the CMS seam).

Sanitizes em dashes on output (L006): captions are copied verbatim from
Instagram, and a faithful copy is not a licence to leak one into a generated file.
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
DRAFTS = PROJECT / "events.draft.json"
OUT = PROJECT / "web" / "src" / "data" / "events.ts"


def clean(t: str) -> str:
    t = re.sub(r"\s*—\s*", ", ", t)
    return re.sub(r"\s+", " ", t).strip()


def ts(v) -> str:
    return json.dumps(v, ensure_ascii=False)


def main() -> int:
    drafts = json.loads(DRAFTS.read_text())
    out = ['/**',
           ' * GENERATED by scripts/write_events.py from events.draft.json.',
           ' * Do not hand-edit: corrections belong in vision-findings.json or',
           ' * venue-aliases.json, then re-run extract_flyers.py and this script.',
           ' *',
           ' * Do NOT import this module from a component. All reads go through',
           ' * getEvents.ts, which is the seam a CMS replaces later.',
           ' */',
           '',
           'import type { EventRecord, SourceMeta } from "../types/event";',
           '',
           f'export const SEED_NOTICE = "";',
           '',
           'export const events: EventRecord[] = [']
    for d in drafts:
        djs = ", ".join(
            f'{{ name: {ts(x["name"])}, '
            + (f'instagram: {ts(x["instagram"])}, ' if x.get("instagram") else "")
            + f'confidence: {ts(x["confidence"])} }}'
            for x in d["djs"]) or ""
        assets = ", ".join(
            f'{{ assetId: {ts(a["targetAssetId"])}, aspectRatio: {a["aspectRatio"]}, '
            f'role: {ts(a["role"])}'
            + (f', kind: {ts(a["kind"])}' if a.get("kind") else "")
            + (f', motion: {{ src: {ts(a["motion"]["src"])}, type: {ts(a["motion"]["type"])} }}'
               if a.get("motion") else "")
            + (f', thumbHash: {ts(a["thumbHash"])}' if a.get("thumbHash") else "")
            + (f', credit: {ts(a["credit"])}' if a.get("credit") else "")
            + ' }'
            for a in d["assets"])
        fields = ", ".join(f'{ts(k)}: {ts(v)}' for k, v in d["review"]["fields"].items())
        out += [
            "  {",
            f'    eventId: {ts(d["eventId"])},',
        ]
        if d.get("title"):
            out.append(f'    title: {ts(clean(d["title"]))},')
        out += [
            f'    venue: {{ name: {ts(d["venue"]["name"])}, city: {ts(d["venue"].get("city",""))}, '
            f'address: {ts(d["venue"].get("address",""))}'
            + (f', coords: {{ lat: {d["venue"]["coords"]["lat"]}, lon: {d["venue"]["coords"]["lon"]} }}'
               if d["venue"].get("coords") else "")
            + ' },',
            f'    date: {ts(d["date"])},',
        ]
        if d.get("endDate"):
            out.append(f'    endDate: {ts(d["endDate"])},')
        if d.get("timeText"):
            out.append(f'    timeText: {ts(d["timeText"])},')
        out.append(f'    djs: [{djs}],')
        if d.get("specialGuests"):
            out.append('    specialGuests: [' + ", ".join(
                f'{{ name: {ts(x["name"])}'
                + (f', instagram: {ts(x["instagram"])}' if x.get("instagram") else "")
                + ' }' for x in d["specialGuests"]) + '],')
        if d.get("presentedBy"):
            out.append('    presentedBy: [' + ", ".join(
                f'{{ name: {ts(x["name"])}'
                + (f', instagram: {ts(x["instagram"])}' if x.get("instagram") else "")
                + (', alsoPerforms: true' if x.get("alsoPerforms") else "")
                + ' }' for x in d["presentedBy"]) + '],')
        if d.get("info"):
            out.append(f'    info: {ts(clean(d["info"]))},')
        out += [
            f'    assets: [{assets}],',
            f'    source: {{ igShortcode: {ts(d["shortcode"])}, caption: {ts(clean(d["source"]["caption"]))} }},',
            f'    review: {{ fields: {{ {fields} }}, needsHumanReview: {"true" if d["review"]["needsHumanReview"] else "false"} }},',
            "  },",
        ]
    out += ["];", "", "export const sourceMeta: SourceMeta[] = [];", ""]
    text = "\n".join(out)
    if "—" in text:
        print("FAILED: an em dash reached the output"); return 1
    OUT.write_text(text)
    print(f"  wrote {OUT.relative_to(PROJECT)}: {len(drafts)} events, {sum(len(d['assets']) for d in drafts)} assets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
